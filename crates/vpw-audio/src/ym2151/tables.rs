#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_envelope_shift_is_one_a_u32_can_take() {
        // These index `1 << shift` on a 32-bit counter. A value of 88 got in
        // here once, copied from the scaling the table above needs and this one
        // does not; it panics in debug and wraps to a different, wrong shift in
        // release. Nothing in the chip needs a shift past 11.
        for (i, &shift) in EG_RATE_SHIFT.iter().enumerate() {
            assert!(
                shift < 32,
                "EG_RATE_SHIFT[{i}] = {shift} overflows a u32 shift"
            );
        }
        assert_eq!(EG_RATE_SHIFT.iter().copied().max(), Some(11));
    }

    #[test]
    fn every_envelope_rate_selects_a_real_row() {
        // `EG_RATE_SELECT` is an offset into `EG_INC` and gets 0..=7 added to
        // it, so the largest entry plus seven still has to be in range.
        let worst = EG_RATE_SELECT.iter().copied().max().unwrap() as usize + 7;
        assert!(worst < EG_INC.len(), "{worst} is past the end of EG_INC");
    }
}
